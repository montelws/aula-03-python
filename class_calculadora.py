def somar (a, b):
    """Soma dois números."""
    return a + b

def subtrair (a, b):
    """Subtrai dois números."""
    return a - b

def multiplicar (a, b):
    """Multiplica dois números."""
    return a * b

def dividir (a, b):
    """Divide dois números."""
    return a / b